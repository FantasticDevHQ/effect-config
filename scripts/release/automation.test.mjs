import assert from "node:assert/strict"
import { test } from "node:test"
import { validatePullRequest } from "../pr-standard.mjs"
const repo = "FantasticDevHQ/effect-config"
const sha = "a".repeat(40)
const pr = () => ({ state: "open", base: { ref: "main", repo: { full_name: repo } }, head: { ref: "release-please--branches--main", sha, repo: { full_name: repo } } })
async function feature(name) {
  const module = await import("./automation.mjs").catch(() => ({}))
  assert.equal(typeof module[name], "function", `${name} is missing`)
  return module[name]
}
const notes = "## [0.1.1](https://github.com/FantasticDevHQ/effect-config/compare/v0.1.0...v0.1.1) (2026-11-19)\n\n### Bug Fixes\n\n* Handle config errors"
const generated = `Release candidate\n---\n\n${notes}\n\n---\nGenerated by Release Please`
test("release metadata satisfies the real validator and preserves parseable exact notes", async () => {
  const body = (await feature("releaseBody"))({ body: generated, repository: repo, runId: "123", attempt: "2", sha })
  const commit = { sha, message: "chore(main): FORG-162 release 0.1.1\n\nNo-ticket: automated release\n" }
  assert.deepEqual(validatePullRequest({ title: "chore(main): FORG-162 release 0.1.1", body }, ["CHANGELOG.md"], [commit]), [])
  assert.match(validatePullRequest({ title: "chore(main): FORG-162 release 0.1.1", body }, [], [{ sha, message: "chore(main): FORG-162 release 0.1.1" }]).join(), /has no ticket or issue reference/)
  assert.equal(body.split("\n---\n")[1].trim(), notes)
  assert.match(body, /actions\/runs\/123\/attempts\/2/)
  assert.match(body, /pnpm check.*passed/)
  assert.match(body, /Session\/thread ID: 123:2/)
})
test("release metadata refuses ambiguous notes and missing automation identity", async () => {
  const run = await feature("releaseBody")
  for (const body of ["no delimiters", "header\n---\nnot a version\n---\nfooter", generated + "\n---\nextra"]) {
    assert.throws(() => run({ body, repository: repo, runId: "123", attempt: "1", sha }))
  }
  assert.throws(() => run({ body: generated, repository: repo, runId: "", attempt: "1", sha }))
})
test("auto-merge is pinned to the current generated PR head", async () => {
  const calls = []
  const result = await (await feature("enableReleaseAutoMerge"))({ repository: repo, prNumber: 10, command: async args => {
    calls.push(args)
    return args[0] === "api" ? JSON.stringify(pr()) : ""
  } })
  assert.equal(result, "enabled")
  assert.deepEqual(calls[1], ["pr", "merge", "10", "--repo", repo, "--auto", "--squash", "--match-head-commit", sha])
})
test("auto-merge refuses unrelated PRs before attempting a merge", async () => {
  const run = await feature("enableReleaseAutoMerge")
  for (const change of [p => p.head.ref = "main", p => p.head.repo.full_name = "other/repo", p => p.base.ref = "develop", p => p.head.sha = "bad"]) {
    const data = pr(); change(data)
    const calls = []
    await assert.rejects(run({ repository: repo, prNumber: 10, command: async args => { calls.push(args); return JSON.stringify(data) } }), /generated release PR/)
    assert.equal(calls.length, 1)
  }
})
test("auto-merge retries only explicit stale-head errors, with fresh SHA and bounded attempts", async () => {
  const run = await feature("enableReleaseAutoMerge")
  let reads = 0, merges = 0
  const stale = () => Object.assign(new Error("stale"), { stderr: "expected head oid does not match the current head oid" })
  await assert.rejects(run({ repository: repo, prNumber: 10, wait: async () => {}, command: async args => {
    if (args[0] === "api") { reads++; return JSON.stringify(pr()) }
    merges++; throw stale()
  } }), /stale/)
  assert.equal(reads, 3); assert.equal(merges, 3)
  merges = 0
  await assert.rejects(run({ repository: repo, prNumber: 10, command: async args => {
    if (args[0] === "api") return JSON.stringify(pr())
    merges++; throw new Error("permission denied")
  } }), /permission denied/)
  assert.equal(merges, 1)
})

test("workflow routes main maintenance, generated releases, manual tags and recovery without duplicate publish", async () => {
  const { readFileSync } = await import("node:fs")
  const workflow = readFileSync(new URL("../../.github/workflows/release.yml", import.meta.url), "utf8")
  const condition = workflow.slice(workflow.indexOf("\n  verify:"), workflow.indexOf("\n  publish:")).match(/if: >-\n([\s\S]*?)\n    env:/)[1].trim()
  const evaluate = new Function("github", "inputs", "needs", "always", "cancelled", "startsWith", `return (${condition.replaceAll("needs.release-please", 'needs["release-please"]')})`)
  for (const [ref, event, tag, created, result, expected] of [
    ["refs/heads/main", "push", "", "", "success", false],
    ["refs/heads/main", "push", "", "true", "success", true],
    ["refs/tags/v0.1.1", "push", "", "", "skipped", true],
    ["refs/heads/main", "workflow_dispatch", "v0.1.0", "", "skipped", true],
    ["refs/heads/topic", "push", "", "", "skipped", false],
    ["refs/heads/main", "push", "", "", "failure", false],
  ]) {
    assert.equal(evaluate({ ref, event_name: event }, { release_tag: tag }, { "release-please": { result, outputs: { release_created: created } } }, () => true, () => false, (s, prefix) => s.startsWith(prefix)), expected)
  }
})

