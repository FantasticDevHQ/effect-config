test("amend adds the footer once, keeps author and subject, and force-pushes with a lease", async () => {
  const amend = await feature("amendReleaseCommit")
  const { execFileSync } = await import("node:child_process")
  const { mkdtempSync, rmSync, writeFileSync } = await import("node:fs")
  const { tmpdir } = await import("node:os")
  const { join } = await import("node:path")
  const root = mkdtempSync(join(tmpdir(), "release-amend-"))
  const sh = (cwd, ...args) => execFileSync("git", args, { cwd, encoding: "utf8" }).trim()
  const title = "chore(main): FORG-162 release 0.1.2"
  const branch = "release-please--branches--main--components--@fantastic.dev/effect-config"
  try {
    const remote = join(root, "remote.git"), dir = join(root, "work")
    sh(root, "init", "-q", "--bare", remote)
    sh(root, "init", "-q", "-b", "main", dir)
    sh(dir, "config", "user.name", "Fixture"); sh(dir, "config", "user.email", "fixture@example.invalid")
    writeFileSync(join(dir, "CHANGELOG.md"), "# Changelog\n"); sh(dir, "add", "."); sh(dir, "commit", "-q", "-m", "docs: base")
    sh(dir, "checkout", "-q", "-b", branch)
    writeFileSync(join(dir, "CHANGELOG.md"), "# Changelog\n\n## 0.1.2\n"); sh(dir, "add", ".")
    execFileSync("git", ["commit", "-q", "-m", title], { cwd: dir, env: { ...process.env, GIT_AUTHOR_NAME: "fantasticdev-npm-releases[bot]", GIT_AUTHOR_EMAIL: "1+bot@users.noreply.github.com", GIT_AUTHOR_DATE: "2026-11-21T07:11:46Z", GIT_COMMITTER_DATE: "2026-11-21T07:11:46Z" } })
    sh(dir, "remote", "add", "origin", remote); sh(dir, "push", "-q", "origin", branch)
    const before = sh(dir, "rev-parse", "HEAD")
    const result = await amend({ dir, branch })
    assert.equal(result.amended, true)
    assert.equal(sh(remote, "rev-parse", `refs/heads/${branch}`), result.sha)
    assert.equal(sh(dir, "log", "-1", "--format=%B").trimEnd(), `${title}\n\nNo-ticket: automated release`)
    assert.equal(sh(dir, "log", "-1", "--format=%an <%ae> %aI"), "fantasticdev-npm-releases[bot] <1+bot@users.noreply.github.com> 2026-11-21T07:11:46Z")
    assert.equal(sh(dir, "rev-parse", "HEAD~1"), sh(dir, "rev-parse", "main"))
    assert.equal(sh(dir, "rev-parse", "HEAD^{tree}"), sh(dir, "rev-parse", `${before}^{tree}`))
    assert.equal((await amend({ dir, branch })).amended, false)
    // A newer candidate pushed meanwhile is never overwritten.
    sh(dir, "reset", "-q", "--hard", before); sh(dir, "commit", "-q", "--amend", "-m", "chore(main): FORG-162 release 0.1.3")
    const newer = sh(dir, "rev-parse", "HEAD")
    sh(dir, "push", "-q", "--force", "origin", `${newer}:refs/heads/${branch}`); sh(dir, "reset", "-q", "--hard", before)
    await assert.rejects(amend({ dir, branch }), /stale info|rejected/)
    assert.equal(sh(remote, "rev-parse", `refs/heads/${branch}`), newer)
    await assert.rejects(amend({ dir, branch: "main" }), /non-release branch/)
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})

